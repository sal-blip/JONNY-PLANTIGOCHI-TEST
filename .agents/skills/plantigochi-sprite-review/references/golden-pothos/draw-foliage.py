"""Draw the approved Golden pothos foliage at its native game resolution."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw


def draw_foliage():
    image = Image.new("RGBA", (65, 67))
    pen = ImageDraw.Draw(image)
    palette = {
        "ink": "#254638", "shade": "#235544", "lows": "#36674c",
        "green": "#397552", "leaf": "#59915c", "light": "#8caa67",
        "citron": "#adc073", "gold": "#dbbe68", "cream": "#ead787",
        "stalk": "#527054", "litstalk": "#91a36c", "stalkshade": "#3a5945", "node": "#b8af71",
    }

    def line(points, color, width=1):
        pen.line(points, fill=palette[color], width=width)

    def poly(points, color):
        pen.polygon(points, fill=palette[color])

    def leaf(origin, outline, patches, details):
        layer = Image.new("RGBA", image.size)
        mask = Image.new("L", image.size)
        dx, dy = origin

        def offset(points):
            return [(x + dx, y + dy) for x, y in points]

        brush = ImageDraw.Draw(layer)
        ImageDraw.Draw(mask).polygon(offset(outline), fill=255)
        brush.polygon(offset(outline), fill=palette["ink"])
        for color, points in patches:
            brush.polygon(offset(points), fill=palette[color])
        for color, points in details:
            brush.line(offset(points), fill=palette[color])
        layer.putalpha(mask)
        image.alpha_composite(layer)

    # The stems fork at the old petiole scar. A single runner drapes toward the shelf.
    line([(32,44),(31,41),(30,37),(27,34),(23,32),(21,30)],'stalkshade',2)
    line([(31,42),(31,39),(28,35),(25,33),(22,32)],'litstalk')
    line([(31,43),(33,38),(34,34),(35,29),(37,24),(40,21)],'stalkshade',2)
    line([(32,41),(34,36),(35,31),(37,26),(38,24)],'litstalk')
    # Runner swells gently at the two nodes.
    line([(32,44),(34,39),(38,36),(43,35),(47,37),(50,41),(51,45),(51,47),(53,51),(55,53)],'stalkshade',2)
    line([(34,40),(37,37),(40,36),(43,36),(46,37),(48,39),(50,43)],'litstalk')
    line([(51,46),(52,49),(55,52)],'stalk')
    line([(46,37),(47,37)],'node')
    line([(51,45),(52,46)],'node')
    # New rolled leaf points through the gap. A single sliver of gold at the seam.
    poly([(31,38),(29,34),(29,31),(30,30),(30,26),(32,29),(33,31),(33,34)],'shade')
    poly([(31,36),(30,33),(30,29),(31,28),(32,32)],'light')
    line([(30,27),(31,30),(31,32)],'gold')
    # Upper-right mature blade. The inner lobe curls inward at the notch, the tip turns to the right.
    leaf((33,14),
     [(0,8),(0,6),(1,4),(3,2),(5,2),(7,3),(8,5),(9,5),(10,2),(12,1),(14,1),(17,3),(19,6),(20,9),(20,14),(19,18),(19,21),(20,23),(17,22),(12,19),(8,17),(5,14),(3,13),(1,11)],
     [
     ('lows',[(1,6),(4,3),(6,3),(8,6),(10,6),(11,3),(13,2),(15,2),(18,5),(19,8),(19,15),(18,20),(19,22),(13,18),(9,16),(4,13),(1,9)]),
     ('green',[(1,6),(3,4),(5,3),(7,4),(8,7),(10,6),(11,3),(14,2),(16,3),(18,6),(18,10),(17,13),(17,17),(18,20),(14,17),(12,15),(8,14),(4,11),(2,10)]),
     ('leaf',[(2,6),(4,4),(6,4),(8,6),(10,7),(12,8),(13,11),(15,14),(15,16),(12,14),(9,13),(6,12),(4,10),(4,8)]),
     ('light',[(2,6),(4,5),(6,4),(7,6),(9,7),(10,9),(12,10),(11,11),(8,9),(6,9),(6,8),(4,8)]),
     ('gold',[(4,5),(6,5),(7,7),(9,7),(9,9),(7,8),(6,8),(5,7),(3,7)]),
     ('leaf',[(11,5),(13,3),(15,3),(16,4),(16,6),(15,5),(14,5),(13,8),(12,8)]),
     ('light',[(14,4),(15,4),(14,7),(13,8)]),
     ('shade',[(15,13),(17,15),(18,13),(18,16),(17,19),(17,20),(15,17),(13,16)]),
     ],
     [('cream',[(4,5),(5,5)]),('light',[(9,7),(11,9),(12,11),(15,14)]),('leaf',[(15,15),(18,20)]),('green',[(2,8),(2,9)])])
    # Broad forward-facing leaf. Its long drip tip falls left, away from the pot.
    leaf((9,23),
     [(0,10),(1,7),(3,4),(6,2),(8,2),(11,4),(13,5),(15,2),(17,0),(20,0),(22,2),(23,5),(23,8),(21,12),(18,15),(12,18),(7,21),(2,24),(2,20),(1,17),(0,14)],
     [
     ('lows',[(1,10),(2,7),(4,5),(7,3),(9,3),(13,6),(16,3),(18,1),(20,1),(22,3),(22,8),(20,11),(17,14),(11,17),(6,21),(2,23),(3,21),(2,16),(1,14)]),
     ('green',[(2,9),(4,6),(7,4),(9,4),(12,6),(14,6),(16,3),(19,1),(21,3),(22,6),(20,9),(17,11),(15,13),(11,15),(7,18),(4,20),(2,20),(3,15),(2,13)]),
     ('leaf',[(2,9),(4,6),(7,4),(9,4),(12,6),(13,7),(11,10),(9,12),(7,14),(6,16),(3,19),(3,16),(2,13)]),
     ('light',[(3,8),(5,6),(7,5),(9,5),(11,6),(12,8),(9,10),(9,12),(7,11),(6,13),(4,12),(3,14),(3,11)]),
     ('gold',[(4,8),(7,5),(9,5),(10,6),(10,7),(8,7),(7,9),(9,8),(8,10),(6,11),(6,9),(4,10),(3,11)]),
     ('cream',[(5,7),(7,5),(8,5),(7,7),(6,7),(5,9)]),
     ('leaf',[(16,5),(18,2),(20,2),(21,3),(20,5),(18,5),(15,8),(14,8)]),
     ('light',[(17,4),(19,2),(20,2),(19,4),(17,5),(16,6)]),
     ('shade',[(12,15),(15,13),(17,13),(19,10),(21,9),(19,12),(16,15),(12,16),(7,20),(4,21),(8,17)]),
     ('light',[(11,10),(13,8),(16,8),(14,9),(12,10),(10,12)]),
     ('citron',[(8,14),(9,13),(8,15),(7,15),(5,18)]),
     ],
     [('citron',[(13,7),(11,9),(9,12)]),('leaf',[(6,17),(4,20)]),('green',[(20,4),(21,5)]),('cream',[(6,10),(7,9)])])
    # Trailing juvenile leaf lies outside the pot; its two lobes have a shallower notch.
    leaf((44,43),
     [(0,4),(1,2),(3,1),(5,1),(7,4),(8,2),(10,0),(12,0),(14,2),(15,5),(15,8),(13,11),(10,14),(7,18),(6,16),(3,13),(1,10),(0,7)],
     [
     ('lows',[(1,4),(3,2),(5,2),(7,5),(9,3),(11,1),(13,1),(14,4),(14,8),(12,11),(9,14),(7,17),(5,14),(2,10),(1,7)]),
     ('green',[(1,4),(3,2),(5,2),(7,5),(9,4),(11,1),(13,2),(14,5),(13,8),(10,11),(8,14),(7,16),(5,13),(3,10),(2,8)]),
     ('leaf',[(2,4),(3,3),(5,3),(6,5),(8,6),(10,4),(11,6),(9,9),(8,12),(7,14),(5,12),(4,9),(3,8)]),
     ('light',[(2,4),(4,3),(5,4),(5,5),(6,5),(8,7),(7,9),(6,9),(5,7),(3,7)]),
     ('gold',[(3,4),(4,4),(4,5),(6,6),(6,8),(5,8),(4,6),(3,6)]),
     ('leaf',[(10,4),(11,2),(13,2),(12,4),(10,6)]),
     ('citron',[(7,9),(9,7),(9,8),(7,12)]),
     ('shade',[(11,11),(13,9),(11,12),(9,13),(8,15)]),
     ],[('cream',[(3,4),(4,5)]),('light',[(8,6),(8,8)]),('leaf',[(7,13),(7,15)])])

    # Broken golden marbling follows the secondary veins. Keep broad, asymmetrical
    # patches so the cultivar reads even at shelf scale.
    poly([(14,30),(16,28),(17,28),(17,29),(19,30),(17,31),(17,33),(15,34),(16,31),(13,32)],'gold')
    line([(14,30),(16,29),(16,28)],'cream')
    poly([(19,33),(22,30),(24,30),(23,31),(21,32),(19,35),(17,36)],'citron')
    line([(20,32),(22,31)],'cream')
    poly([(25,34),(28,31),(29,31),(28,33),(26,33),(25,35),(23,36)],'light')
    line([(23,36),(21,37),(19,39)],'green')
    line([(18,38),(17,39),(15,40)],'light')
    poly([(38,19),(39,19),(41,21),(42,21),(44,23),(43,24),(41,23),(40,23),(41,24),(39,23),(38,21),(36,21)],'gold')
    line([(37,20),(38,20),(39,21)],'cream')
    poly([(46,21),(47,19),(48,18),(48,20),(47,21),(47,23),(45,24)],'citron')
    line([(46,22),(47,20)],'gold')
    poly([(45,26),(47,26),(49,28),(50,28),(50,30),(48,29),(47,29)],'leaf')
    line([(47,30),(49,31),(51,33)],'green')
    # A smaller, mostly green new blade hangs past the rim at the end of the runner.
    poly([(46,47),(48,46),(49,47),(49,48),(51,50),(50,51),(48,49),(47,49)],'citron')
    line([(47,47),(48,47)],'cream')
    line([(54,49),(55,47),(56,46)],'light')
    poly([(53,51),(55,50),(54,52),(52,53),(51,55)],'light')
    line([(49,52),(50,53),(51,55)],'green')
    # A short emerging leaf has a folded, pale edge. Its base stays attached to the crown.
    poly([(30,37),(30,33),(28,30),(28,27),(27,25),(30,26),(32,29),(33,32),(32,35)],'shade')
    poly([(30,34),(30,32),(29,30),(28,27),(30,28),(32,31),(32,33)],'light')
    line([(28,26),(29,28),(30,29),(31,31)],'gold')
    line([(31,34),(31,36),(32,37),(32,40)],'stalk')

    # A new lateral leaf alternates with the tip at the bend of the runner.
    line([(46,37),(44,36),(42,37),(41,38)],'stalkshade')
    leaf((35,35),[(0,7),(1,4),(2,3),(5,2),(6,3),(8,1),(10,1),(10,4),(9,6),(6,8),(2,9),(0,11)],[
     ('lows',[(1,7),(2,4),(5,3),(6,4),(9,2),(9,5),(7,7),(2,9),(1,10)]),
     ('green',[(1,7),(3,4),(5,3),(6,4),(9,2),(8,5),(5,7),(2,8)]),
     ('leaf',[(2,6),(3,4),(5,4),(6,5),(4,6),(2,8)]),
     ('light',[(3,5),(4,4),(5,4),(4,6),(2,7)])
     ],[('citron',[(3,5),(4,5)]),('green',[(7,5),(6,6)])])

    return image


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="Destination PNG file")
    draw_foliage().save(parser.parse_args().output)
