"""Encode the approved shop tiles and split out the repottable foliage."""
import argparse
from pathlib import Path
from runpy import run_path
from tempfile import TemporaryDirectory

from PIL import Image

REFERENCE = Path(__file__).resolve().parent
encode = run_path(str(REFERENCE.parent.parent / 'scripts' / 'encode-sprite.py'))['encode']
OUTPUT = REFERENCE.parents[4] / 'src' / 'shopSprites' / 'approved.js'

# The y coordinate is the pot's contact point. Trailing foliage may hang below it.
BASELINES = {
    'terra': 55, 'wave': 55, 'oak': 55, 'lacquer': 55, 'neko': 55, 'record': 55,
    'golden-pothos': 32, 'snake-plant': 55, 'hoya-serpens-splash': 28,
    'queen-anthurium': 30, 'monkey-tail-cactus': 26,
}
TRAILING = {
    'hoya-serpens-splash': (35, 12),
    'queen-anthurium': (36, 15),
    'monkey-tail-cactus': (35, 8),
}
ROOM_SCALE = 1.65


def is_pottery(sku, x, y, rgb):
    r, g, b = rgb
    if sku == 'snake-plant':
        return y >= 42 or y >= 39 and r > g + 5 and r > b + 20
    if sku == 'monkey-tail-cactus':
        return 25 <= x <= 47 and y < 26 and r > g + 6
    return 20 <= x <= 44 and 15 <= y < 32 and r >= g + 2


def foliage_for(sku, tile):
    if sku in {'hoya-serpens-splash', 'queen-anthurium'}:
        leaves = Image.new('RGBA', tile.size)
        with Image.open(REFERENCE / 'sprites' / (sku + '.png')) as source:
            leaves.alpha_composite(source.convert('RGBA'), (23, 5))
        return leaves

    leaves = tile.copy()
    for y in range(tile.height):
        for x in range(tile.width):
            r, g, b, a = tile.getpixel((x, y))
            if a and is_pottery(sku, x, y, (r, g, b)):
                leaves.putpixel((x, y), (0, 0, 0, 0))
    return leaves


def object_code(png, baseline, center=36):
    lines = encode(png, center, baseline).decode().splitlines()[1:]
    return ['    ' + prop.removeprefix('export const ').replace(' = ', ': ', 1).rstrip(';') + ','
            for prop in lines[:2]] + ['    spriteRows: [', *['    ' + row for row in lines[3:-1]], '    ],']


def compile_sprites():
    lines = ['// Generated by phase-1-shop-pass-02/encode-approved.py.', 'export const approvedArt = {']
    with TemporaryDirectory() as work:
        path = Path(work) / 'layer.png'
        for sku, baseline in BASELINES.items():
            master = REFERENCE / 'tiles' / (sku + '.png')
            lines.extend([f'  "{sku}": {{', *object_code(master, baseline), '  },'])
            if sku in {'terra', 'wave', 'oak', 'lacquer', 'neko', 'record'}:
                continue
            with Image.open(master) as source:
                tile = source.convert('RGBA')
            leaves = foliage_for(sku, tile)
            leaves.save(path)
            lines.extend([f'  "{sku}-foliage": {{', *object_code(path, baseline), '  },'])
            for y in range(tile.height):
                for x in range(tile.width):
                    if leaves.getpixel((x, y))[3]:
                        tile.putpixel((x, y), (0, 0, 0, 0))
            tile.save(path)
            lines.extend([f'  "{sku}-pot": {{', *object_code(path, baseline), '  },'])
            if sku in TRAILING:
                x, y = TRAILING[sku]
                bounds = leaves.getbbox()
                crop = leaves.crop(bounds)
                scaled = crop.resize(tuple(round(n * ROOM_SCALE) for n in crop.size), Image.Resampling.NEAREST)
                scaled.save(path)
                center = round((x - bounds[0]) * ROOM_SCALE)
                crown = round((y - bounds[1]) * ROOM_SCALE)
                lines.extend([f'  "{sku}-repotted": {{', *object_code(path, crown, center), '  },'])
    return '\n'.join([*lines, '};', f'export const featuredRoomScale = {ROOM_SCALE};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generated = compile_sprites()
    if parser.parse_args().check:
        if OUTPUT.read_text() != generated:
            parser.exit(1, f'{OUTPUT} differs from the approved masters.\n')
    else:
        OUTPUT.write_text(generated)
