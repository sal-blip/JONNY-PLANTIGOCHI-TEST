"""Encode an opaque-pixel PNG on transparency into a synchronous JavaScript sprite."""

import argparse
import json
from pathlib import Path

from PIL import Image


def encode(path, anchor_x, anchor_y):
    with Image.open(path) as source:
        pixels = source.convert("RGBA")
    bounds = pixels.getchannel("A").getbbox()
    if bounds is None:
        raise ValueError("The image contains no visible pixels.")

    left, top, right, bottom = bounds
    palette = {}
    rows = []
    for y in range(top, bottom):
        row = []
        for x in range(left, right):
            r, g, b, alpha = pixels.getpixel((x, y))
            if alpha == 0:
                row.append(" ")
                continue
            if alpha != 255:
                raise ValueError(f"Partially transparent pixel at ({x}, {y}).")
            color = f"#{r:02x}{g:02x}{b:02x}"
            if color not in palette:
                if len(palette) == 256:
                    raise ValueError("An indexed sprite supports up to 256 opaque colors.")
                palette[color] = chr(ord("A") + len(palette))
            row.append(palette[color])
        rows.append("".join(row).rstrip(" "))

    output = [
        "// Generated by encode-sprite.py. Space is transparent. A is palette index 0.",
        f"export const spriteOffset = {{x:{left - anchor_x}, y:{top - anchor_y}}};",
        "export const spritePalette = " + json.dumps(list(palette)) + ";",
        "export const spriteRows = [",
        *["  " + json.dumps(row) + "," for row in rows],
        "];",
    ]
    return ("\n".join(output) + "\n").encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--anchor", nargs=2, type=int, metavar=("X", "Y"), required=True,
                        help="sprite origin in source image coordinates")
    parser.add_argument("--check", action="store_true",
                        help="compare the generated bytes with the existing output file")
    args = parser.parse_args()
    try:
        generated = encode(args.source, *args.anchor)
        if args.check:
            if args.output.read_bytes() != generated:
                parser.exit(1, f"{args.output} differs from the encoded source.\n")
        else:
            args.output.write_bytes(generated)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
